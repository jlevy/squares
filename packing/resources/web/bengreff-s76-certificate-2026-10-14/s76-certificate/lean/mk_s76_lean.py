"""Emit Sqpack/S76T/Pts.lean (cover data + kernel-checked data facts) and Sqpack/S76Lower.lean
(s(76) = 9 from the covering hypothesis) for a "mixed 1" cover on [0,9]^2.
usage: python mk_s76_lean.py COVER LEANROOT"""
import sys, os, hashlib
cover, root = sys.argv[1], sys.argv[2]
sys.path.insert(0, os.path.join(root, "scripts")); sys.path.insert(0, os.path.join(root, "..", "search"))
import gen_zmmtree as Z
G = Z.G
toks = [ln.split() for ln in open(cover) if ln.strip() and not ln.startswith("#")]
assert toks[0] == ["mixed", "1"] and toks[1] == ["9", "1"]
D, W, m = int(toks[2][0]), int(toks[3][0]), int(toks[4][0])
agg = {}
for X, Y, w in (map(int, t) for t in toks[5:5 + m]):
    if w > 0: agg[(X, Y)] = agg.get((X, Y), 0) + w
Pts = sorted((x, y, w) for (x, y), w in agg.items())
k = int(toks[5 + m][0])
sagg = {}
for t in toks[6 + m:6 + m + k]:
    a, b, c, d, w = map(int, t)
    if w <= 0: continue
    key = tuple(sorted([(a, b), (c, d)]))          # canonical endpoint order
    sagg[key] = sagg.get(key, 0) + w
Sg = sorted((p[0], p[1], q[0], q[1], w) for (p, q), w in sagg.items())
Mq = 9 * D; n = 76
tot = sum(p[2] for p in Pts) + sum(s[4] for s in Sg)
assert tot < n * W, "total not below 76"
sha = hashlib.sha256(open(cover, "rb").read()).hexdigest()
name = "S76T"; ns = "SquarePacking." + name
os.makedirs(os.path.join(root, "Sqpack", name), exist_ok=True)
doc = (f"/-!\n# `{name}`: the s(76) mixed cover (generated by mk_s76_lean.py; do not edit)\n\n"
       f"From `{os.path.basename(cover)}`, sha256 `{sha}`:\n{len(Pts)} points `(X/{D}, Y/{D})` and {len(Sg)} segments, "
       f"masses `w/{W}`, container `[0, {Mq}/{D}]²`, total `{tot}/{W}` < 76.\n-/\n")
L = ["import Sqpack.ZMTreeX\n", Z.HDR, doc, f"namespace {ns}\n", "open BoxTree ZMTreeM\n",
     "set_option maxRecDepth 100000 in\nset_option maxHeartbeats 0 in",
     f"noncomputable def pts : PTree :=\n  {G.emit_ptree(Pts)}\n",
     "theorem pts_nodup : pts.toList.Nodup :=\n  PTree.nodup_of_chainB _ (by decide +kernel)\n",
     f"theorem pts_d4 : d4Check {Mq} pts = true := by decide +kernel\n",
     "set_option maxRecDepth 100000 in\nset_option maxHeartbeats 0 in",
     f"noncomputable def segs : STree :=\n  {Z.emit_stree(Sg)}\n",
     f"theorem segs_d4 : segD4Check {Mq} segs = true := by decide +kernel\n",
     f"theorem wsum_lt : pts.wsum + segs.wsum < {n} * {W} := by decide +kernel\n",
     f"end {ns}\n"]
open(os.path.join(root, "Sqpack", name, "Pts.lean"), "w").write("\n".join(L))
S = 4096; R = 2 ** 32; Um = 2 ** 31; half = f"({Mq} * {S} - {Mq} * {S} / 2)"
top = f'''import Sqpack.S76T.Pts
import Sqpack.Attain

/-!
# `s(76) = 9` from a certified covering statement

`S76T.pts`, `S76T.segs` are the mixed cover `{os.path.basename(cover)}` (sha256 `{sha}`):
{len(Pts)} points and {len(Sg)} axis-parallel segments of `[0,9]²`, masses `w/{W}`, total `< 76`
(kernel-checked in `S76T/Pts.lean`, with its exact D4 invariance).

`S76Cover` is the covering statement on the D4 fundamental region, in the sense of `CovM`:
every closed unit square inside `[0,9]²` with centre in `[0,9/2]²` and angle `2 arctan u`,
`u ∈ [0, 1/2]`, captures mass `≥ 1`. It is the statement the external exact checkers certify
(Evan Daniel's `zm_mixed.py`, and `zmx2`); it is a hypothesis here, not proved in Lean.
From it, `le_minSide_mixed` (Evan Daniel's `Sqpack`, unchanged) gives `s(76) ≥ 9`, and the 9×9
grid gives `s(76) ≤ 9`.
-/

namespace SquarePacking

open BoxTree ZMTreeM S76T

/-- The certified covering statement (hypothesis). -/
def S76Cover : Prop :=
  CovM {D} {S} {Mq} {R} {W} pts.toList segs.toList 0 {half} 0 {half} 0 {Um}

/-- **`s(76) ≥ 9`**, assuming the covering statement. -/
theorem s76_ge_9 (hcov : S76Cover) : (9 : ℝ) ≤ minSide 76 := by
  have h := le_minSide_mixed {D} {S} {Mq} {R} {Um} {W} pts segs (by norm_num) (by norm_num) (by norm_num)
    (by norm_num) pts_nodup pts_d4 segs_d4 hcov 76 9 wsum_lt (by norm_num)
  norm_num at h ⊢
  exact h

/-- **`s(76) = 9`**, assuming the covering statement. -/
theorem s76_eq_9 (hcov : S76Cover) : minSide 76 = 9 := by
  have h1 := s76_ge_9 hcov
  have hp : Packs 76 9 := by
    have h := packs_grid 9 76 (by norm_num)
    simpa using h
  have hb : BddBelow {{s | Packs 76 s}} := by
    by_contra hnb
    rw [minSide, Real.sInf_of_not_bddBelow hnb] at h1
    norm_num at h1
  exact le_antisymm (csInf_le hb hp) h1

end SquarePacking
'''
open(os.path.join(root, "Sqpack", "S76Lower.lean"), "w").write(top)
print("points %d segments %d total %.9f" % (len(Pts), len(Sg), tot / W))
