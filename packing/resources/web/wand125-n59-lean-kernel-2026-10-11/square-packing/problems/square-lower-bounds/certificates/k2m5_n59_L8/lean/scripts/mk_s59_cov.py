#!/usr/bin/env python3
"""Write `Sqpack/S59T/Cov.lean` (the cover of the D4 fundamental region from the root cells of the
batches) and `Sqpack/S59Lower.lean` (`s(59) = 8`).

    mk_cov.py BATCHES.json LEANDIR

BATCHES.json: {"<batch>": ["i,j", ...], ...}, every root cell of the 80 x 80 grid in exactly one batch.
"""
import json, os, sys

batches = json.load(open(sys.argv[1]))
L = sys.argv[2]
D, S, Mq, R, W = 1000, 4096, 8000, 2 ** 32, 10 ** 8
Um = R // 2
M = Mq * S
half = M - M // 2
cells = 80
width = half // cells
assert width * cells == half
where = {}
for b, cs in batches.items():
    for c in cs:
        i, j = map(int, c.split(','))
        assert (i, j) not in where, c
        where[(i, j)] = int(b)
assert len(where) == cells * cells, len(where)
covT = f"CovM {D} {S} {Mq} {R} {W} ptsL segsL"


def gx(i0, i1):
    if i1 - i0 == 1:
        return gy(i0, 0, cells)
    m = (i0 + i1) // 2
    return f"(CovM.splitX {m * width}\n  {gx(i0, m)}\n  {gx(m, i1)})"


def gy(i, j0, j1):
    if j1 - j0 == 1:
        return f"B{where[(i, j0)]}.r_{i}_{j0}"
    m = (j0 + j1) // 2
    return f"(CovM.splitY {m * width} {gy(i, j0, m)} {gy(i, m, j1)})"


root = f"0 {half} 0 {half} 0 {Um}"
imports = "\n".join(f"import Sqpack.S59T.B{b}.Roots" for b in sorted(map(int, batches)))
txt = "\n".join([
    imports + "\n",
    "set_option linter.style.longLine false\n",
    "/-!\n# `S59T`: the mixed box tree covers the D4 fundamental region (generated; do not edit)\n\n"
    f"The {cells * cells} root cells of width `{width}` (the theorems `B<batch>.r_<i>_<j>` of the batches' "
    "`Roots`), assembled by halving `x`, then `y`.\n-/\n",
    "namespace SquarePacking.S59T\n", "open BoxTree ZMTreeM\n",
    "set_option maxRecDepth 100000 in",
    f"theorem cov_rootL : {covT} {root} :=\n  {gx(0, cells)}\n",
    f"theorem cov_root : CovM {D} {S} {Mq} {R} {W} pts.toList segs.toList {root} := by\n"
    "  rw [pts_toList, segs_toList]; exact cov_rootL\n",
    "end SquarePacking.S59T\n"])
open(os.path.join(L, "Sqpack/S59T/Cov.lean"), "w").write(txt)

low = f"""import Sqpack.S59T.Cov
import Sqpack.Attain

/-!
# `s(59) = 8`, kernel-checked

The mixed cover `n59_mixed_cover_8.txt` (26,308 points and 5,240 axis-parallel segments of
`[0,8]²`, masses `w/10⁸`, total `< 59`) gives every closed unit square inside `[0,8]²` mass `≥ 1`;
`Sqpack/S59T/*` is its box tree over the D4 fundamental region (generated by
`lean/scripts/gen_zmmtree.py`; every chunk is `decide +kernel` of `ZMTreeM.checkM`, proved sound once,
`ZMTreeM.soundM`), and `le_minSide_mixed` turns it into the lower bound.  The 8×8 grid gives the
upper bound.
-/

namespace SquarePacking

open BoxTree ZMTreeM S59T

/-- **`s(59) ≥ 8`**: 59 unit squares do not fit in a square of side `< 8`. -/
theorem s59_ge_8 : (8 : ℝ) ≤ minSide 59 := by
  have h := le_minSide_mixed {D} {S} {Mq} {R} {Um} {W} pts segs (by norm_num) (by norm_num) (by norm_num)
    (by norm_num) pts_nodup pts_d4 segs_d4 cov_root 59 8 wsum_lt (by norm_num)
  norm_num at h ⊢
  exact h

/-- **`s(59) = 8`**. -/
theorem s59_eq_8 : minSide 59 = 8 := by
  have h1 := s59_ge_8
  have hp : Packs 59 8 := by
    have h := packs_grid 8 59 (by norm_num)
    simpa using h
  have hb : BddBelow {{s | Packs 59 s}} := by
    by_contra hnb
    rw [minSide, Real.sInf_of_not_bddBelow hnb] at h1
    norm_num at h1
  exact le_antisymm (csInf_le hb hp) h1

end SquarePacking
"""
open(os.path.join(L, "Sqpack/S59Lower.lean"), "w").write(low)
print("wrote Cov.lean and S59Lower.lean", len(txt), "bytes")
