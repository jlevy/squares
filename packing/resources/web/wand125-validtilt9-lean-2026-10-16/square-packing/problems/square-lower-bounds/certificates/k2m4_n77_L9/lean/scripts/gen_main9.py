#!/usr/bin/env python3
"""`Sqpack/V9/Main.lean`: the root grid of run `qxzm_full` (k2m4) glued into the D4 root, and
`ValidTilt9` (hence `Valid9` with Lemma Z, and `s(k² − 4) = k` for all `k ≥ 8`).

    gen_main9.py [OUTDIR]
"""
import os, sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from tree_rebuild import load  # noqa: E402
from run_v7 import LEAVES, SG, RG, MQ  # noqa: E402

D, W = 5, 2 * 10 ** 12
Q = D * SG


def main(outdir):
    roots = [(i, r) for i, (r, l, u) in enumerate(load(LEAVES))]
    xs = sorted({r[0] for _, r in roots} | {r[1] for _, r in roots})
    ys = sorted({r[2] for _, r in roots} | {r[3] for _, r in roots})
    us = sorted({r[4] for _, r in roots} | {r[5] for _, r in roots})
    at = {(xs.index(r[0]), ys.index(r[2]), us.index(r[4])): i for i, r in roots}
    assert len(at) == (len(xs) - 1) * (len(ys) - 1) * (len(us) - 1) == len(roots)
    iq = lambda x: int(x * Q)
    ir = lambda u: int(u * RG)
    assert all((x * Q).denominator == 1 for x in xs + ys) and all((u * RG).denominator == 1 for u in us)

    def glue(a0, a1, b0, b1, c0, c1):
        if a1 - a0 == 1 and b1 - b0 == 1 and c1 - c0 == 1:
            return f"root_{at[(a0, b0, c0)]:05d}"
        if c1 - c0 > 1:
            m = (c0 + c1) // 2
            return f"(CovT.splitU {ir(us[m])} {glue(a0, a1, b0, b1, c0, m)} {glue(a0, a1, b0, b1, m, c1)})"
        if a1 - a0 >= b1 - b0:
            m = (a0 + a1) // 2
            return f"(CovT.splitX {iq(xs[m])} {glue(a0, m, b0, b1, c0, c1)} {glue(m, a1, b0, b1, c0, c1)})"
        m = (b0 + b1) // 2
        return f"(CovT.splitY {iq(ys[m])} {glue(a0, a1, b0, m, c0, c1)} {glue(a0, a1, m, b1, c0, c1)})"

    assert xs[0] == 0 and ys[0] == 0 and us[0] == 0 and xs[-1] == ys[-1] == F(9, 2) and us[-1] == F(1, 2)
    half = MQ * SG - MQ * SG // 2
    lines = ["import Sqpack.V9.Tilt", "import Sqpack.V9.Bridge"]
    lines += [f"import Sqpack.V9.R{i:05d}" for i, _ in roots]
    lines += ["", "/-!", "# `ValidTilt9`, kernel-checked", "",
              "The pose trees of `qx2_zm` run `qxzm_full` (`certificates/k2m4/qx2_zm`), one module per root",
              "(`R?????.lean`, generated by `scripts/run_v7.py` with the k2m4 constants), glued over the D4 root",
              "`[0, 9/2]² × (0, 1/2]` (`validTilt_of_tree`); the box file as the cover (`Bridge.lean`).",
              "With Lemma Z (`ValidSplit9.lean`) this is `Valid9`, hence `s(k² − 4) = k` for every `k ≥ 8`. -/", "",
              "namespace SquarePacking", "namespace LemmaELeaf", "open ZMTreeM ZMTree", "",
              f"theorem v9_tree : CovT {D} {SG} {MQ} {RG} {W} [] tsegs trects 0 {half} 0 {half} 0 {RG // 2} :=",
              f"  {glue(0, len(xs) - 1, 0, len(ys) - 1, 0, len(us) - 1)}", "",
              "/-- **`ValidTilt9`** (`ValidSplit9.lean`): the tilted region of the box cover `K4_k008_box9.txt`. -/",
              "theorem validTilt9 : Bentz4.ValidTilt9 := by",
              f"  have h := validTilt_of_tree {D} {SG} {MQ} {RG} {RG // 2} {W} PTree.leaf segsT trects",
              "    (by decide) (by decide) (by decide) (by decide) (by rw [segsT_toList]; exact v9_tree) (by decide)",
              "  unfold Bentz4.ValidTilt9",
              "  rw [box9Cover_eq_mcoverP]",
              "  convert h using 1",
              "  norm_num", "",
              "/-- **`Valid9`**, with Lemma Z (`ValidSplit9.lean`). -/",
              "theorem valid9 : Bentz4.Valid9 := Bentz4.valid9_of_tilt validTilt9", "",
              "/-- **`s(k² − 4) = k` for every `k ≥ 8`**, with no hypothesis. -/",
              "theorem bentz4 : ∀ k : ℕ, 8 ≤ k → minSide (k ^ 2 - 4) = k := Bentz4.bentz4_of_validTilt9 validTilt9", "",
              "end LemmaELeaf", "end SquarePacking"]
    open(os.path.join(outdir, "Main.lean"), 'w').write("\n".join(lines) + "\n")
    print(len(roots), "roots;", len(xs) - 1, len(ys) - 1, len(us) - 1)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'Sqpack', 'V9'))
