#!/usr/bin/env python3
"""Generate `frontier/RESULTS.md`: the register's results, prioritized.

`results.yaml` is the record and `epistemics.md` owns its vocabulary; this view
is the one prioritized surface the reader tier points at, sorted by
significance descending, then confirmation descending, then id.
`devtools/check_results.py` grants the rungs; this file only displays them,
and the gate fails when the committed view drifts from the register.

This project's results come first, credited to Levy by name and to the authors each
rests on directly (`result_credit.credit_line`, from the entry's `builds_on`). Results
by others follow in the lineage their sources state, read from the bibliography rather
than restated: building on this project, crediting it second-hand, independent of it,
and published before it began.
Within each group the entries still waiting on a replay here (`C` below `C3`) come
first, since they are the queue. Their credit and published date are shown beside the
rungs. Every row of both tables states the result's `kind`, what the result is: a
lower bound, an upper bound, optimality, or one of the kinds that are no bound on
`s(n)`. Every row ends its ratings with the result's status (`devtools.result_status`,
the function the site's tables use): recorded, reviewed, confirmed or incomplete,
derived from the rungs and the cited evidence and never stored; then who has the next
move, where the register records an `activity`; then `superseded`, with the results that
supersede it (`devtools.render_recent_results.position_marks`): for a bound no case bound
rests on now, the results its cases' bounds rest on instead, both derived from the case
records; for a result of another kind, the later results its entry declares imply it
(`superseded_by`), and `superseded in part` where they imply only some of it.

Usage, from `packing/`:
    uv run --frozen --all-extras --group dev python -m devtools.render_results --update
    uv run --frozen --all-extras --group dev python -m devtools.render_results --check
"""

from __future__ import annotations

import argparse
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from strif import atomic_output_file

from devtools.check_results import confirmation_code, kind_label
from devtools.register_prose import paragraphs
from devtools.render_recent_results import load_records, position_marks, standing
from devtools.result_credit import OTHERS, credit_line, source_lineage
from devtools.result_status import CONFIRMED, status, status_line
from devtools.verifier_registry import LABELS, entry_line
from devtools.verifier_registry import load as load_verifiers
from sqpack.yamlio import safe_load

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "frontier" / "results.yaml"
BIBLIOGRAPHY = ROOT / "resources" / "bibliography.yaml"
OUTPUT = ROOT / "frontier" / "RESULTS.md"

#: The typographic apostrophe the register's prose uses, written as an escape for the
#: reason `tests/test_generated_table_typography.py` gives: a literal one is invisible in a
#: diff and ambiguous on sight.
APOSTROPHE = "\u2019"


#: The title of the first group: this project's own results.
OURS = f"This Project{APOSTROPHE}s Results"

HEADER = """# Results

<!-- GENERATED by devtools.render_results --update from results.yaml. Do not edit. -->

One row per registered result: this project's first, then results by others grouped
by the lineage their sources state, each sorted by significance, then confirmation.
A result's kind says what it is: a lower bound, an upper bound, optimality (an exact
value), or one of the kinds [`epistemics.md`](../../epistemics.md#result-kinds) defines
for a result that is no bound on `s(n)`.
Every credit names people: `X`, or `X after Y` where X's result rests directly on Y's
proof, method or tool.
The axes are defined in [`epistemics.md`](../../epistemics.md): `V` is the
verification the result carries as certified by its own source, `C` how far that
verification has been independently confirmed here or by a third party, `S` a
judged score that never gates, and novelty a scoped source-search classification.
Rung 4 on either axis needs adversarial AI review and a retained human oversight
record; rung 5, formal verification reviewed by human experts; a rung-3 result is
machine-checked with its review record pending.
`devtools/check_results.py` validates the structural support and required
explanations for every declared `V` and `C`.
A result's status says how far the work on it here has gone, and follows `C`:
*recorded* (`C0`), *reviewed* (`C1`), *confirmed* (`C2` and up), or *incomplete* while a
defect found in it is open. After it come who has the next move, where one is recorded,
and *superseded* by the results named, where the result is a bound that no case bound
rests on now, or a result of another kind that a later result implies; *superseded in
part* says a later result implies some of it and it still holds the rest.
A confirmed result says how it was confirmed, from the code its confirming runs used:
*reproduced with the producer's code*, where they re-ran the code that produced or
verified it; *re-implemented, sharing the producer's components*, where separately
written code reused named parts of it; *independently re-implemented*, where code that
shares none of it decided the claim. An exact value takes the less independent of its two
halves. [Verification Code](#verification-code) below names every program behind each
result, external or first-party, and [`VERIFIERS.md`](VERIFIERS.md) says what each one
is and whose it is.
"""


def _scope(record: dict) -> str:
    scope = record["scope"]
    if "n_values" in scope:
        return ", ".join(str(n) for n in scope["n_values"])
    return f"{scope['n_min']}-{scope['n_max']}"


def claim_cell(record: dict) -> str:
    """The claim in one table cell, its paragraphs kept apart by line breaks."""
    return "<br><br>".join(paragraphs(record["claim"])).replace("|", r"\|")


def next_action(record: dict) -> list[str]:
    """One result's `next_rung` as a list item: its first paragraph on the bullet's line,
    and each later paragraph as a paragraph of the same item, indented under it."""
    first, *rest = paragraphs(record["next_rung"])
    lines = [f"- **{record['id']}** — {first}"]
    for paragraph in rest:
        lines += ["", f"  {paragraph}"]
    if rest:
        # A blank line closes a multi-paragraph item, so the next bullet starts clean.
        lines.append("")
    return lines


def confirmed_how(record: Mapping[str, Any], evidence: Mapping[str, Mapping[str, Any]]) -> str:
    """How a confirmed result was confirmed, as the status cell says it: the label of
    `check_results.confirmation_code`, or nothing."""
    code = confirmation_code(record, [evidence[ref] for ref in record["evidence"]])
    return LABELS[code] if code else ""


def verification_code(
    results: list[dict], evidence: Mapping[str, Mapping[str, Any]]
) -> list[str]:
    """The section naming every program behind each result: one item per result, its
    status said in full, and one line per cited evidence entry with who ran it, how its
    code stands to the producer's, and its programs, each marked external or
    first-party (`verifier_registry.entry_line`)."""
    verifiers = load_verifiers()
    lines = [
        "## Verification Code",
        "",
        (
            "The programs behind each result, by its cited evidence: who ran each check, "
            "how the code that ran stands to the code the result's producer used, and "
            "which programs they are, each external or first-party. A premise check "
            "verifies inputs or receipts and leaves the decision to the program beside it."
        ),
        "",
    ]
    for record in sorted(results, key=lambda item: item["id"]):
        held = status(record, evidence)
        how = confirmed_how(record, evidence) if held == CONFIRMED else ""
        lines.append(f"- **{record['id']}** — {held}{f', {how}' if how else ''}")
        lines.extend(
            f"  - {entry_line(evidence[ref], verifiers)}"
            for ref in record["evidence"]
            if ref in evidence
        )
    lines.append("")
    return lines


def order(record: dict) -> tuple[int, int, str]:
    """Significance descending, then confirmation descending, then id."""
    return (-record["significance"]["score"], -int(record["confirmation"][1]), record["id"])


def load_sources() -> dict[str, dict]:
    """The bibliography's sources, by key."""
    return {
        source["key"]: source
        for source in safe_load(BIBLIOGRAPHY.read_text(encoding="utf-8"))["sources"]
    }


def grouped_results(
    register: dict, sources: dict[str, dict] | None = None
) -> list[tuple[str, list[dict]]]:
    """The register's results in the groups and the order `RESULTS.md` shows them.

    This project's results first, by `order`; then results by others, one group per
    lineage in `OTHERS` order, each with the entries still waiting on a replay here
    (`C` below `C3`) ahead of the rest and `order` within both. Empty groups of others
    are left out. Every view that lists the register reads this, so none can disagree
    with `RESULTS.md` about where a result sits.
    """
    sources = load_sources() if sources is None else sources
    results = sorted(register["results"], key=order)
    ours = [record for record in results if not record.get("attribution")]
    others = [record for record in results if record.get("attribution")]
    groups: list[tuple[str, list[dict]]] = [(OURS, ours)]
    for key, title in OTHERS:
        group = sorted(
            (record for record in others if source_lineage(record, sources) == key),
            key=lambda record: (int(record["confirmation"][1]) >= 3, *order(record)),
        )
        if group:
            groups.append((title, group))
    return groups


def render() -> str:
    register = safe_load(RESULTS.read_text(encoding="utf-8"))
    sources = load_sources()
    (_, ours), *others = grouped_results(register, sources)
    results = sorted(register["results"], key=order)
    lines = [HEADER]
    lines.append(f"## {OURS}")
    lines.append("")
    records = load_records()
    evidence = records.register.evidence

    def status(record: dict) -> str:
        position = position_marks(record, standing(record, records), records)
        return status_line(record, evidence, position, how=confirmed_how(record, evidence))

    lines.append("| id | n | kind | credit | V | C | S | status | novelty | claim |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    lines.extend(
        f"| {record['id']} | {_scope(record)} | {kind_label(record['kind'])} "
        f"| {credit_line(record, sources)} "
        f"| {record['verification']} "
        f"| {record['confirmation']} | S{record['significance']['score']} "
        f"| {status(record)} | {record['novelty']} | {claim_cell(record)} |"
        for record in ours
    )
    lines.append("")
    if others:
        lines.append("## Results by Others")
        lines.append("")
        lines.append(
            f"Credit is the source{APOSTROPHE}s, as the bibliography records it; `V` and `C` "
            f"are this register{APOSTROPHE}s, so an entry below `C3` is still waiting on a "
            "complete replay here."
        )
        lines.append("")
        for title, group in others:
            lines.append(f"### {title}")
            lines.append("")
            lines.append("| id | n | kind | credit | published | V | C | S | status | claim |")
            lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
            lines.extend(
                f"| {record['id']} | {_scope(record)} | {kind_label(record['kind'])} "
                f"| {credit_line(record, sources)} "
                f"| {record['attribution']['published']} | {record['verification']} "
                f"| {record['confirmation']} | S{record['significance']['score']} "
                f"| {status(record)} | {claim_cell(record)} |"
                for record in group
            )
            lines.append("")
    lines.extend(verification_code(results, evidence))
    lines.append("## Next actions")
    lines.append("")
    lines.append("The next evidence-improving action or terminal rationale for each result:")
    lines.append("")
    for record in results:
        lines.extend(next_action(record))
    lines.append("")
    lines.append(f"Register reviewed {register['last_reviewed']}.")
    lines.append("")
    lines.append("<!-- This document follows common-doc-guidelines.md.")
    lines.append("See github.com/jlevy/practical-prose and review guidelines before editing.")
    lines.append("-->")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--update", action="store_true")
    group.add_argument("--check", action="store_true")
    options = parser.parse_args()
    rendered = render()
    if options.update:
        with atomic_output_file(OUTPUT) as temporary:
            temporary.write_text(rendered, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT.parent)}")
        return 0
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
        relative = OUTPUT.relative_to(ROOT.parent)
        print(f"{relative} is stale; run devtools.render_results --update")
        return 1
    print(f"{OUTPUT.relative_to(ROOT.parent)} agrees with results.yaml")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
