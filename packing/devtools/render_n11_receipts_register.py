@dataclass(frozen=True)
class Scan:
    """What one receipt's files say, read once."""

    name: str
    file_count: int
    size: int
    status: str | None
    sample: tuple[str, ...]
    result_sha256: frozenset[str]
    file_sha256: frozenset[str]
    objects: frozenset[str]
    names_cited: frozenset[str]
    hashes_cited: frozenset[str]
    registry: Mapping[str, str] | None
    unread: tuple[str, ...]


@dataclass(frozen=True)
class Binding:
    """Who binds one receipt, derived from the registries and the other receipts."""

    composer_pinned: bool
    capture_join: bool
    pilot_registry: bool
    exclusion_inventory: bool
    baseline_inventory: bool
    field_inventory: bool
    by_result_hash: tuple[str, ...]
    by_path: tuple[str, ...]
    by_object: tuple[str, ...]
    paper: bool
    validation_guide: bool

    def labels(self) -> list[str]:
        flags = (
            self.composer_pinned,
            self.capture_join,
            self.pilot_registry,
            self.exclusion_inventory,
            self.baseline_inventory,
            self.field_inventory,
        )
        labels = [label for label, flag in zip(COMPOSER_READ, flags, strict=True) if flag]
        for label, names in (
            ("cited by result hash:", self.by_result_hash),
            ("cited by path:", self.by_path),
            ("object held: cited by", self.by_object),
        ):
            if names:
                labels.append(f"{label} {shown(names)}")
        if self.paper:
            labels.append("paper")
        if self.validation_guide:
            labels.append("validation guide")
        return labels

    @property
    def composer_read(self) -> bool:
        return any(label in COMPOSER_READ for label in self.labels())

    @property
    def cited(self) -> bool:
        return bool(self.by_result_hash or self.by_path or self.by_object)


def shown(names: Sequence[str]) -> str:
    if len(names) <= NAMES_SHOWN:
        return ", ".join(names)
    return ", ".join(names[:NAMES_SHOWN]) + f" +{len(names) - NAMES_SHOWN} more"


def hashes_in(data: bytes) -> set[str]:
    """Every maximal run of exactly 64 lowercase hex digits, found without a regex.

    A regex pays per byte, and most of the decoded bytes here are long decimal numbers,
    which are hex digits too; marking runs with a byte table is about four times faster.
    """
    flags = np.frombuffer(b"\0" + data.translate(HEX_FLAGS) + b"\0", dtype=np.int8)
    edges = np.flatnonzero(np.diff(flags))
    starts, ends = edges[0::2], edges[1::2]
    return {data[start : start + 64].decode() for start in starts[ends - starts == 64].tolist()}


def names_in(data: bytes) -> set[str]:
    return {token.decode().rstrip(".") for token in PATH_TOKEN.findall(data)}


def decoded(path: Path, raw: bytes) -> bytes:
    return zlib.decompress(raw, wbits=31) if path.name.endswith(".gz") else raw


def is_text(path: Path) -> bool:
    return path.name.endswith((*TEXT_SUFFIXES, ".json.gz"))


def object_name(path: Path, receipt: Path) -> str | None:
    """The hex identity of a file stored under an `objects/` directory, if it has one."""
    stem = path.name.split(".", 1)[0]
    in_store = "objects" in path.relative_to(receipt).parts[:-1]
    return stem if in_store and HEX_NAME.fullmatch(stem) else None


def status_of(record: Any) -> str | None:
    status = record.get("status") if isinstance(record, dict) else None
    return status if isinstance(status, str) else None


def scan(name: str) -> Scan:
    path = RECEIPTS / name
    files = [path] if path.is_file() else sorted(p for p in path.rglob("*") if p.is_file())
    names: set[str] = set()
    hashes: set[str] = set()
    file_sha: set[str] = set()
    objects: set[str] = set()
    unread: list[str] = []
    for file in files:
        stored = object_name(file, path) if path.is_dir() else None
        if stored:
            objects.add(stored)
        if not is_text(file):
            continue
        if file.name.endswith(".gz") and file.stat().st_size > LARGEST_SCANNED_GZIP:
            unread.append(file.relative_to(RECEIPTS).as_posix())
            continue
        raw = file.read_bytes()
        file_sha.add(hashlib.sha256(raw).hexdigest())
        data = decoded(file, raw)
        names |= names_in(data)
        hashes |= hashes_in(data)
    result = path if path.is_file() else _result_file(path)
    record: Any = None
    result_sha: set[str] = set()
    if result is not None:
        raw = result.read_bytes()
        data = decoded(result, raw)
        result_sha = {hashlib.sha256(raw).hexdigest(), hashlib.sha256(data).hexdigest()}
        record = json.loads(data) if result.name.endswith((".json", ".json.gz")) else None
    registry = None
    if path.is_file() and isinstance(record, dict):
        registry = next((record[key] for key in COMPOSER_REGISTRY_KEYS if key in record), None)
    direct = sorted(p.name for p in path.iterdir() if p.is_file()) if path.is_dir() else []
    return Scan(
        name=name,
        file_count=len(files),
        size=sum(file.stat().st_size for file in files),
        status=status_of(record),
        sample=tuple((direct or [f.name for f in files])[:NAMES_SHOWN]),
        result_sha256=frozenset(result_sha),
        file_sha256=frozenset(file_sha),
        objects=frozenset(objects),
        names_cited=frozenset(names - {name}),
        hashes_cited=frozenset(hashes),
        registry=registry,
        unread=tuple(unread),
    )


def _result_file(directory: Path) -> Path | None:
    for candidate in ("result.json", "result.json.gz"):
        if (directory / candidate).is_file():
            return directory / candidate
    return None


def receipt_names() -> list[str]:
    """Every receipt on disk: each directory and each top-level file but this register."""
    return sorted(path.name for path in RECEIPTS.iterdir() if path != REGISTER)


def _receipt_of(recorded: str) -> str:
    return (REPO / recorded).resolve().relative_to(RECEIPTS.resolve()).parts[0]


def inventory_bound(relative: str, key: str) -> frozenset[str]:
    record = json.loads((RECEIPTS / relative).read_bytes())
    return frozenset(_receipt_of(row["path"]) for row in record[key])


@cache
def scans() -> dict[str, Scan]:
    return {name: scan(name) for name in receipt_names()}


@cache
def bindings() -> dict[str, Binding]:
    """Derive every receipt's binding from the registries and the other receipts' text."""
    every = scans()
    captured = {receipt for receipt, _, _ in CAPTURE.values()}
    piloted = {relative.split("/", 1)[0] for relative in PILOTS}
    exclusion = inventory_bound(EXCLUSION_INVENTORY, "execution_record_bindings")
    baseline = inventory_bound(BASELINE_INVENTORY, "execution_record_bindings")
    field = inventory_bound(FIELD_INVENTORY, "accepted_receipts")
    paper = names_in(TEMPLATE.read_bytes())
    guides = set().union(*(names_in(guide.read_bytes()) for guide in GUIDES))
    outputs = {name for name, item in every.items() if item.registry is not None}
    result: dict[str, Binding] = {}
    for name, item in every.items():
        pinned = name in FIXED or bool(item.file_sha256 & COMPOSER_PINNED_FILES)
        # A structured binding already says what its source file's citation would say.
        restated = {name}
        restated |= {EXCLUSION_INVENTORY} if name in exclusion else set()
        restated |= {"baseline-d4-cuts"} if name in baseline else set()
        restated |= {"field-batch-a"} if name in field else set()
        restated |= outputs if pinned else set()
        others = [other for other in every.values() if other.name not in restated]
        by_hash = [o.name for o in others if o.hashes_cited & item.result_sha256]
        by_path = [o.name for o in others if name in o.names_cited and o.name not in by_hash]
        by_object = [
            o.name
            for o in others
            if o.hashes_cited & (item.objects - o.objects)
            and o.name not in by_hash
            and o.name not in by_path
        ]
        result[name] = Binding(
            composer_pinned=pinned,
            capture_join=name in captured,
            pilot_registry=name in piloted,
            exclusion_inventory=name in exclusion,
            baseline_inventory=name in baseline,
            field_inventory=name in field,
            by_result_hash=tuple(by_hash),
            by_path=tuple(by_path),
            by_object=tuple(by_object),
            paper=name in paper,
            validation_guide=name in guides,
        )
    return result


def tier_contradictions() -> dict[str, str]:
    """Curated tiers that the derived bindings contradict, with the reason for each."""
    found: dict[str, str] = {}
    every = scans()
    for name, entry in ENTRIES.items():
        binding = bindings().get(name)
        if binding is None:
            continue
        current_output = every[name].registry == FIXED
        if entry.tier == "composed" and not (binding.composer_read or current_output):
            found[name] = "curated composed, but nothing the composer reads binds it"
        elif entry.tier in {"attempt", "control", "replacement", "ancestry"} and (
            binding.composer_read
        ):
            found[name] = f"curated {entry.tier}, but the composer reads it"
        elif entry.tier == "ancestry" and not binding.cited:
            found[name] = "curated ancestry, but no other receipt cites it"
    return found


def size_text(size: int) -> str:
    return f"{size / 1e6:.1f} MB" if size >= 1_000_000 else f"{size / 1e3:.1f} KB"


def bound_text(name: str) -> str:
    labels = bindings()[name].labels()
    if labels:
        return "; ".join(labels)
    return f"**nothing**; kept as {ENTRIES[name].kept}"


def status_text(item: Scan) -> str:
    if item.status:
        return f"`{item.status}`"
    if (RECEIPTS / item.name).is_file():
        return "—"
    return ", ".join(f"`{name}`" for name in item.sample)


def link(name: str) -> str:
    return f"[`{name}/`]({name}/)" if (RECEIPTS / name).is_dir() else f"[`{name}`]({name})"


def ordered(names: Iterable[str]) -> list[str]:
    order = list(TIERS)
    return sorted(names, key=lambda name: (order.index(ENTRIES[name].tier), name))


def tier_table() -> list[str]:
    every = scans()
    rows = ["| Tier | What it is | Receipts | Size |", "| --- | --- | ---: | ---: |"]
    for tier, meaning in TIERS.items():
        members = [name for name in every if ENTRIES[name].tier == tier]
        size = sum(every[name].size for name in members)
        rows.append(f"| {tier} | {meaning} | {len(members)} | {size_text(size)} |")
    total = sum(item.size for item in every.values())
    rows.append(f"| **all** | | {len(every)} | {size_text(total)} |")
    return rows


def receipt_table() -> list[str]:
    every = scans()
    rows = [
        "| Receipt | Tier | Purpose | Status | Files | Size | Bound by |",
        "| --- | --- | --- | --- | ---: | ---: | --- |",
    ]
    for name in ordered(every):
        item, entry = every[name], ENTRIES[name]
        rows.append(
            f"| {link(name)} | {entry.tier} | {entry.purpose} | {status_text(item)} | "
            f"{item.file_count} | {size_text(item.size)} | {bound_text(name)} |"
        )
    return rows


def legend() -> list[str]:
    unread = [path for item in scans().values() for path in item.unread]
    unread_text = ", ".join(f"`{path}`" for path in unread) or "none"
    items = (
        (
            "**composer, pinned**: the final composer reads it at a hash fixed in its own "
            "modules: `FIXED` in `packing/devtools/inventory_n11_completion.py`, or the pinned "
            "field inventory, nonfield manifest and exclusion inventory."
        ),
        (
            "**capture join** and **pilot registry**: `CAPTURE` or `PILOTS` in the same "
            "modules names it as one capture node's or one case's accepted execution."
        ),
        (
            "**exclusion inventory**, **baseline inventory**, **field inventory**: a recorded "
            "execution path in `exclusion-inventory.json`, "
            "`baseline-d4-cuts/baseline-execution-inventory.json` or "
            "`field-batch-a/field-coverage-inventory.json` falls inside it."
        ),
        (
            "**cited by result hash** and **cited by path**: another receipt's text contains "
            "the SHA-256 of its `result.json` (stored or decoded; for a top-level file, the "
            "file itself), or the path `receipts/<name>`."
        ),
        (
            "**object held**: another receipt cites, by hash, an object stored under its "
            "`objects/` that the citer does not store itself."
        ),
        (
            "**paper** and **validation guide**: the review article's template, or the "
            "packet's `VALIDATION.md` or `README.md`, links it."
        ),
    )
    notes = (
        "Each citing receipt is listed once, under the strongest relation, and a citation "
        "that only restates a structured binding, such as the inventory naming a batch or "
        "the composer's own output files, is not repeated. Text means every `.json`, "
        "`.jsonl`, `.sh`, `.txt`, `.md` and `.log` file and every `.json.gz` decoded; a "
        "`.json.gz` over 2 MB on disk is a retained source state, not a record of a run, "
        f"and is not read. Not read: {unread_text}."
    )
    lines = [wrap(f"- {item}", indent="  ") for item in items]
    return ["\n".join(lines), wrap(notes)]


def wrap(text: str, indent: str = "") -> str:
    return textwrap.fill(
        text,
        width=WIDTH,
        subsequent_indent=indent,
        break_long_words=False,
        break_on_hyphens=False,
    )


def render() -> str:
    parts = [f"# {TITLE}", *(wrap(paragraph) for paragraph in PURPOSE)]
    parts += ["## Tiers", "\n".join(tier_table())]
    parts += ["## Receipts", "\n".join(receipt_table())]
    parts += ["## How the Binding Column Is Derived", *legend()]
    parts.append(FOOTER)
    return "\n\n".join(parts) + "\n"


def parser() -> argparse.ArgumentParser:
    command = argparse.ArgumentParser(description=__doc__)
    command.add_argument("--check", action="store_true", help="fail if the register is stale")
    return command


def main(argv: Sequence[str] | None = None) -> int:
    arguments = parser().parse_args(argv)
    missing = sorted(set(receipt_names()) - set(ENTRIES))
    if missing:
        print(f"receipts without a curated entry: {', '.join(missing)}", file=sys.stderr)
        return 1
    expected = render()
    current = REGISTER.read_text(encoding="utf-8") if REGISTER.exists() else ""
    if arguments.check:
        if current != expected:
            print("receipts/README.md is stale; rerun the renderer", file=sys.stderr)
            return 1
        print("  n11 receipts register matches the receipts")
        return 0
    if current != expected:
        with atomic_output_file(REGISTER) as temporary:
            temporary.write_text(expected, encoding="utf-8")
        print("rendered n11 receipts register")
    else:
        print("n11 receipts register already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
