def route(name: str) -> Route:
    return ROUTES[name]()


def _read(path: Path) -> bytes:
    data = path.read_bytes()
    return gzip.decompress(data) if path.suffix == ".gz" else data


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def escape_counts(paths: Sequence[Path]) -> dict[str, int]:
    """Occurrences of each kernel-escape token in these Lean sources, comments aside."""
    counts: dict[str, int] = dict.fromkeys(ESCAPES, 0)
    for path in paths:
        text = strip_comments(path.read_text(encoding="utf-8"))
        for token in ESCAPES:
            counts[token] += len(re.findall(token, text, flags=re.MULTILINE))
    return counts


def probe_text(spec: Route) -> str:
    lines = [f"import {name}" for name in spec.probe_imports]
    lines.append("")
    lines += [f"#check @{name}" for name in spec.theorems]
    lines += [f"#print axioms {name}" for name in spec.theorems]
    return "\n".join(lines) + "\n"


def control_text(control: Control, stage_dir: Path) -> str:
    if not control.source:
        return control.text
    text = (stage_dir / control.source).read_text(encoding="utf-8")
    if text.count(control.old) != 1:
        msg = f"{control.name}: the text to mutate occurs {text.count(control.old)} times"
        raise SystemExit(msg)
    return text.replace(control.old, control.new)


def _manifest_revs(path: Path) -> dict[str, str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return {package["name"]: package["rev"] for package in data["packages"]}


def stage(spec: Route, out: Path) -> dict[str, Any]:
    """Write the route's tree under ``out`` from retained bytes, then ``verify`` it."""
    for name in {Path(staged.path).parts[0] for staged in spec.files}:
        target = out / name
        if target.is_dir():
            shutil.rmtree(target)
        elif target.exists():
            target.unlink()
    for staged in spec.files:
        target = out / staged.path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(_read(REPO / staged.origin))
    project = out / spec.project
    (project / "controls").mkdir(exist_ok=True)
    (project / "Probe.lean").write_text(probe_text(spec), encoding="utf-8")
    for control in spec.controls:
        (project / control.path).write_text(control_text(control, out), encoding="utf-8")
    return verify(spec, out)


def verify(spec: Route, out: Path) -> dict[str, Any]:
    """Bind the staged tree under ``out``: each file's upstream digest, the pins, the
    kernel-escape scan, and the probe and controls the route writes."""
    problems: list[str] = []
    files: list[dict[str, Any]] = []
    for staged in spec.files:
        target = out / staged.path
        if not target.is_file():
            problems.append(f"{staged.path}: not staged")
            continue
        data = target.read_bytes()
        digest, blob = _sha256(data), git_blob(data)
        if staged.sha256 and digest != staged.sha256:
            problems.append(
                f"{staged.path}: SHA-256 {digest[:12]}, upstream {staged.sha256[:12]}"
            )
        if staged.blob and blob != staged.blob:
            problems.append(f"{staged.path}: Git blob {blob[:12]}, upstream {staged.blob[:12]}")
        if not (staged.sha256 or staged.blob):
            problems.append(f"{staged.path}: bound by no upstream digest")
        files.append(
            {"path": staged.path, "origin": staged.origin, "sha256": digest, "blob": blob}
        )
    project = out / spec.project
    toolchain = (project / "lean-toolchain").read_text(encoding="utf-8").strip()
    if toolchain != spec.toolchain:
        problems.append(f"lean-toolchain is {toolchain}, the route pins {spec.toolchain}")
    revs = _manifest_revs(project / "lake-manifest.json")
    if revs.get("mathlib") != spec.mathlib:
        problems.append(f"the manifest's Mathlib is {revs.get('mathlib')}, not {spec.mathlib}")
    lean_files = sorted(
        out / staged.path for staged in spec.files if staged.path.endswith(".lean")
    )
    found = escape_counts(lean_files)
    problems += [
        f"{count} x {token} in the staged sources" for token, count in found.items() if count
    ]
    probe = project / "Probe.lean"
    if not probe.is_file() or probe.read_text(encoding="utf-8") != probe_text(spec):
        problems.append("Probe.lean is not the route's probe")
    for control in spec.controls:
        path = project / control.path
        if not path.is_file() or path.read_text(encoding="utf-8") != control_text(control, out):
            problems.append(f"{control.path} is not the route's control")
    return {
        "route": spec.name,
        "upstream": spec.upstream,
        "ok": not problems,
        "problems": problems,
        "toolchain": toolchain,
        "mathlib": revs.get("mathlib"),
        "files": files,
        "kernel_escapes": found,
        "probe": f"{spec.project}/Probe.lean",
        "probe_sha256": _sha256(probe.read_bytes()) if probe.is_file() else None,
        "notes": list(spec.notes),
    }


def _digest_list(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        if line.strip():
            digest, name = line.split(maxsplit=1)
            out[name] = digest
    return out


def _taskset(cpus: str | None) -> list[str]:
    return ["taskset", "-c", cpus] if cpus else []


def generate(
    spec: Route, out: Path, receipts: Path, *, nproc: int, cpus: str | None
) -> dict[str, Any]:
    """Run the route's generator under a receipt and compare its files with the list."""
    gen = spec.generation
    if gen is None:
        msg = f"{spec.name} has no generation step"
        raise SystemExit(msg)
    outdir = out / gen.outdir
    if outdir.exists():
        shutil.rmtree(outdir)
    argv = [*_taskset(cpus), sys.executable, *(arg.format(nproc=nproc) for arg in gen.argv)]
    receipts.mkdir(parents=True, exist_ok=True)
    footer = replay_receipt.run(
        argv,
        receipt=receipts / "gen.log",
        cwd_label=f"{gen.cwd}/ of the stage of {spec.name}",
        python_note=f"{sys.executable} (Python {platform.python_version()})",
        chdir=out / gen.cwd,
    )
    want = _digest_list((out / gen.digests).read_text(encoding="utf-8"))
    got = (
        {path.name: _sha256(path.read_bytes()) for path in sorted(outdir.glob("*.lean"))}
        if outdir.is_dir()
        else {}
    )
    mismatched = sorted(name for name in want.keys() & got.keys() if want[name] != got[name])
    import numpy as np  # noqa: PLC0415 -- the generator's own dependency, reported here

    report: dict[str, Any] = {
        "kind": GENERATION_KIND,
        "route": spec.name,
        "result": spec.result,
        "bead": spec.bead,
        "command": footer["command"],
        "exit": footer["exit"],
        "wall_seconds": footer["wall_seconds"],
        "cpu_seconds": footer["cpu_seconds"],
        "started_utc": footer["started_utc"],
        "ended_utc": footer["ended_utc"],
        "log": "gen.log",
        "log_sha256": _sha256((receipts / "gen.log").read_bytes()),
        "python": platform.python_version(),
        "numpy": np.__version__,
        "nproc": nproc,
        "cpus": cpus,
        "host": _host(),
        "listed": len(want),
        "generated": len(got),
        "matched": sum(1 for name in want if got.get(name) == want[name]),
        "mismatched": mismatched,
        "missing": sorted(want.keys() - got.keys()),
        "extra": sorted(got.keys() - want.keys()),
        "generated_bytes": sum((outdir / name).stat().st_size for name in got),
        "data_sha256_list": _sha256((out / gen.digests).read_bytes()),
    }
    report["ok"] = (
        footer["exit"] == 0 and report["matched"] == report["listed"] == report["generated"]
    )
    atomic_write_text(receipts / GENERATION_NAME, retained_json.dumps(report))
    return report


def _host() -> dict[str, Any]:
    return {
        "machine": platform.machine(),
        "system": platform.system(),
        "release": platform.release(),
        "cores": os.cpu_count(),
    }


def parse_axioms(text: str) -> dict[str, list[str]]:
    """Each ``#print axioms`` line of ``text``: the theorem and its axioms, in order."""
    found: dict[str, list[str]] = {}
    for match in _DEPENDS.finditer(text):
        found[match.group(1)] = [
            axiom.strip() for axiom in match.group(2).split(",") if axiom.strip()
        ]
    for match in _NO_AXIOMS.finditer(text):
        found[match.group(1)] = []
    return found


def axiom_problems(theorems: Sequence[str], axioms: dict[str, list[str]]) -> list[str]:
    """Why these axioms are not exactly the standard three for every theorem."""
    problems: list[str] = []
    for name in theorems:
        if name not in axioms:
            problems.append(f"{name}: no axiom line printed")
        elif sorted(axioms[name]) != sorted(STANDARD_AXIOMS):
            problems.append(f"{name}: axioms {axioms[name]}")
    return problems


def control_refused(kind: str, exit_code: int, text: str) -> bool:
    """Whether a negative control was refused for its own reason.

    ``refused``: Lean exits non-zero with an error, and not one of the setup faults that
    would make the refusal say nothing about the mutation. ``sorry``: the printed axioms
    carry ``sorryAx``, which acceptance refuses.
    """
    if kind == "refused":
        lowered = text.lower()
        return (
            exit_code != 0
            and "error" in lowered
            and not any(fault in lowered for fault in _SETUP_FAULTS)
        )
    axioms = parse_axioms(text)
    return any("sorryAx" in found for found in axioms.values()) and bool(
        axiom_problems(list(axioms), axioms)
    )


def _step(
    name: str,
    argv: list[str],
    *,
    receipts: Path,
    project: Path,
    label: str,
    time_limit: float | None,
) -> dict[str, Any]:
    log = receipts / f"{name}.log"
    footer = replay_receipt.run(
        argv,
        receipt=log,
        cwd_label=label,
        python_note="not used by this command",
        chdir=project,
        time_limit=time_limit,
    )
    return {
        "name": name,
        "command": footer["command"],
        "log": log.name,
        "log_sha256": _sha256(log.read_bytes()),
        "exit": footer["exit"],
        "wall_seconds": footer["wall_seconds"],
        "cpu_seconds": footer["cpu_seconds"],
        "started_utc": footer["started_utc"],
        "ended_utc": footer["ended_utc"],
    }


def _output(cmd: list[str], cwd: Path) -> str:
    done = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)
    return (done.stdout + done.stderr).strip()


def run(
    spec: Route,
    out: Path,
    receipts: Path,
    *,
    cpus: str | None,
    jobs: int,
    cpu_hours_cap: float,
) -> dict[str, Any]:
    """Build the staged route under receipts, print its axioms and run its controls.

    The first failing build step stops the run, and the receipt keeps it as a failure.
    """
    staged = verify(spec, out)
    project = out / spec.project
    receipts.mkdir(parents=True, exist_ok=True)
    label = f"{spec.project}/ of the stage of {spec.name}"
    prefix = _taskset(cpus)
    cap = cpu_hours_cap * 3600
    steps: list[dict[str, Any]] = []
    problems: list[str] = list(staged["problems"])

    def spent() -> float:
        return sum(float(step["cpu_seconds"]) for step in steps)

    def go(name: str, argv: list[str]) -> bool:
        # A wall limit at the CPU cap's equivalent on the granted cores stops a step that
        # would carry the run past the cap.
        width = len(cpus.split(",")) if cpus else os.cpu_count() or 1
        steps.append(
            _step(
                name,
                [*prefix, *argv],
                receipts=receipts,
                project=project,
                label=label,
                time_limit=max(60.0, (cap - spent()) / width),
            )
        )
        if steps[-1]["exit"] != 0:
            problems.append(f"{name} exited {steps[-1]['exit']}")
            return False
        return True

    ok = go("cache", ["lake", "exe", "cache", "get"])
    for index, group in enumerate(spec.builds):
        if not ok:
            break
        if group == (PARTS,):
            parts = sorted(
                (project / path)
                .relative_to(project)
                .with_suffix("")
                .as_posix()
                .replace("/", ".")
                for path in project.glob(spec.parts_glob)
            )
            if not parts:
                problems.append("no generated parts to build; run generate first")
                ok = False
            # One part per lake process, ``jobs`` at a time, as the source's script does.
            for start in range(0, len(parts), max(1, jobs)):
                batch = parts[start : start + max(1, jobs)]
                if ok and not go(f"build-{index}-{start:03d}", ["lake", "build", *batch]):
                    ok = False
        elif not go(f"build-{index}", ["lake", "build", *group]):
            ok = False
    axioms: dict[str, list[str]] = {}
    controls: list[dict[str, Any]] = []
    if ok and go("probe", ["lake", "env", "lean", "Probe.lean"]):
        axioms = parse_axioms((receipts / "probe.log").read_text(encoding="utf-8"))
        problems += axiom_problems(spec.theorems, axioms)
        for control in spec.controls:
            step = _step(
                f"control-{control.name}",
                [*prefix, "lake", "env", "lean", control.path],
                receipts=receipts,
                project=project,
                label=label,
                time_limit=None,
            )
            text = (receipts / step["log"]).read_text(encoding="utf-8")
            refused = control_refused(control.kind, int(step["exit"]), text)
            controls.append(
                {
                    **step,
                    "control": control.name,
                    "kind": control.kind,
                    "what": control.what,
                    "refused": refused,
                }
            )
            if not refused:
                problems.append(f"control {control.name} was not refused")
    elif ok:
        ok = False
    receipt: dict[str, Any] = {
        "kind": KIND,
        "route": spec.name,
        "result": spec.result,
        "bead": spec.bead,
        "packet": spec.packet,
        "upstream": spec.upstream,
        "toolchain": spec.toolchain,
        "mathlib": spec.mathlib,
        "lean_version": _output([*prefix, "lake", "env", "lean", "--version"], project),
        "lake_version": _output(["lake", "--version"], project),
        "mathlib_checked_out": _output(
            ["git", "-C", ".lake/packages/mathlib", "rev-parse", "HEAD"], project
        ),
        "host": _host(),
        "cpus": cpus,
        "jobs": jobs,
        "stage": staged,
        "steps": steps,
        "theorems": list(spec.theorems),
        "axioms": axioms,
        "controls": controls,
        "cpu_seconds": round(spent() + sum(float(c["cpu_seconds"]) for c in controls), 1),
        "wall_seconds": round(
            sum(float(s["wall_seconds"]) for s in steps)
            + sum(float(c["wall_seconds"]) for c in controls),
            1,
        ),
        "recorded_utc": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
    if receipt["mathlib_checked_out"] != spec.mathlib:
        problems.append(f"Mathlib checked out at {receipt['mathlib_checked_out']}")
    receipt["problems"] = problems
    receipt["verdict"] = "passed" if ok and not problems else "failed"
    atomic_write_text(receipts / RECEIPT_NAME, retained_json.dumps(receipt))
    return receipt


def check(spec: Route, receipts: Path) -> list[str]:
    """Validate a retained receipt offline: what it names, its logs, axioms and controls."""
    path = receipts / RECEIPT_NAME
    if not path.is_file():
        return [f"{path}: no receipt"]
    receipt = json.loads(path.read_text(encoding="utf-8"))
    problems: list[str] = []
    for key, want in (
        ("kind", KIND),
        ("route", spec.name),
        ("result", spec.result),
        ("toolchain", spec.toolchain),
        ("mathlib", spec.mathlib),
        ("mathlib_checked_out", spec.mathlib),
        ("verdict", "passed"),
    ):
        if receipt.get(key) != want:
            problems.append(f"{key} is {receipt.get(key)!r}, expected {want!r}")
    if receipt.get("theorems") != list(spec.theorems):
        problems.append("the receipt's theorems are not the route's")
    for step in [*receipt.get("steps", []), *receipt.get("controls", [])]:
        log = receipts / str(step.get("log"))
        if not log.is_file():
            problems.append(f"{step.get('name')}: log {log.name} is not retained")
        elif _sha256(log.read_bytes()) != step.get("log_sha256"):
            problems.append(f"{step.get('name')}: log {log.name} does not match its digest")
    problems.extend(
        f"{step.get('name')} exited {step.get('exit')}"
        for step in receipt.get("steps", [])
        if step.get("exit") != 0
    )
    probe = receipts / "probe.log"
    printed = parse_axioms(probe.read_text(encoding="utf-8")) if probe.is_file() else {}
    if printed != receipt.get("axioms"):
        problems.append("the receipt's axioms are not what probe.log prints")
    problems += axiom_problems(spec.theorems, printed)
    names = {control.name: control for control in spec.controls}
    seen: set[str] = set()
    for entry in receipt.get("controls", []):
        name = str(entry.get("control"))
        seen.add(name)
        if name not in names:
            problems.append(f"control {name} is not the route's")
            continue
        log = receipts / str(entry.get("log"))
        text = log.read_text(encoding="utf-8") if log.is_file() else ""
        if not control_refused(names[name].kind, int(entry.get("exit", 0)), text):
            problems.append(f"control {name}: its log does not show it refused")
    problems += [f"control {name} did not run" for name in names if name not in seen]
    if spec.generation is not None:
        gen_path = receipts / GENERATION_NAME
        gen = json.loads(gen_path.read_text(encoding="utf-8")) if gen_path.is_file() else {}
        if not gen.get("ok"):
            problems.append("the generation receipt does not show the listed digests matched")
    return problems


def check_generation(spec: Route, receipts: Path) -> list[str]:
    """Validate a retained generation receipt offline."""
    path = receipts / GENERATION_NAME
    if not path.is_file():
        return [f"{path}: no generation receipt"]
    gen = json.loads(path.read_text(encoding="utf-8"))
    problems: list[str] = []
    if gen.get("kind") != GENERATION_KIND or gen.get("route") != spec.name:
        problems.append("the generation receipt is not this route's")
    log = receipts / str(gen.get("log"))
    if not log.is_file() or _sha256(log.read_bytes()) != gen.get("log_sha256"):
        problems.append("gen.log is missing or does not match its digest")
    if spec.generation is not None:
        listing = REPO / next(s.origin for s in spec.files if s.path == spec.generation.digests)
        if _sha256(listing.read_bytes()) != gen.get("data_sha256_list"):
            problems.append("the receipt compared another data-sha256.txt")
        if gen.get("listed") != len(_digest_list(listing.read_text(encoding="utf-8"))):
            problems.append("the receipt's listed count is not data-sha256.txt's")
    if not (
        gen.get("ok")
        and gen.get("exit") == 0
        and gen.get("matched") == gen.get("listed") == gen.get("generated")
        and not gen.get("mismatched")
    ):
        problems.append("the generated files do not all match data-sha256.txt")
    return problems


def _default_receipts(spec: Route) -> Path:
    return WEB / spec.packet / RECEIPT_DIR


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("stage", "generate", "run", "check", "check-generation"):
        cmd = sub.add_parser(name)
        cmd.add_argument("route", choices=sorted(ROUTES))
        if name in {"stage", "generate", "run"}:
            cmd.add_argument("--out", type=Path, required=True, help="stage directory")
        if name != "stage":
            cmd.add_argument("--receipts", type=Path, help="receipt directory")
        if name in {"generate", "run"}:
            cmd.add_argument("--cpus", help="run under taskset on these CPUs, e.g. 2,3")
        if name == "generate":
            cmd.add_argument("--nproc", type=int, default=2, help="generator workers")
        if name == "run":
            cmd.add_argument("--jobs", type=int, default=1, help="parts built at once")
            cmd.add_argument(
                "--cpu-hours-cap", type=float, default=40.0, help="stop the run at this CPU"
            )
    args = parser.parse_args(argv)
    spec = route(args.route)
    receipts = getattr(args, "receipts", None) or _default_receipts(spec)
    if args.command == "stage":
        report = stage(spec, args.out)
        print(json.dumps(report, indent=2))
        return 0 if report["ok"] else 1
    if args.command == "generate":
        staged = stage(spec, args.out)
        if not staged["ok"]:
            print(json.dumps(staged, indent=2))
            return 1
        report = generate(spec, args.out, receipts, nproc=args.nproc, cpus=args.cpus)
        print(json.dumps(report, indent=2))
        return 0 if report["ok"] else 1
    if args.command == "run":
        report = run(
            spec,
            args.out,
            receipts,
            cpus=args.cpus,
            jobs=args.jobs,
            cpu_hours_cap=args.cpu_hours_cap,
        )
        print(json.dumps({k: report[k] for k in ("verdict", "problems", "axioms")}, indent=2))
        return 0 if report["verdict"] == "passed" else 1
    problems = (
        check(spec, receipts) if args.command == "check" else check_generation(spec, receipts)
    )
    for problem in problems:
        print(problem)
    print(f"{spec.name}: {'FAIL' if problems else 'OK'}")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
