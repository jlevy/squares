@dataclass(frozen=True)
class Staged:
    """One staged file: its path in the stage and its retained bytes.

    ``origin`` is repository-relative; a ``.gz`` holds the gzipped upstream bytes.
    ``blob`` is the file's Git blob at the upstream commit, from a closure receipt or
    from ``UPSTREAM_BLOBS``. A file without one is held by its packet's custody alone.
    """

    path: str
    origin: str
    blob: str | None = None


@dataclass(frozen=True)
class Control:
    """A negative control the run must refuse.

    ``refused`` controls must make Lean exit non-zero with an error of their own, not a
    setup fault; ``sorry`` controls must print ``sorryAx`` among a theorem's axioms.
    A control with ``source`` is that staged file with ``old`` replaced by ``new``, where
    ``old`` occurs exactly once; otherwise ``text`` is the whole file.
    """

    name: str
    kind: str
    path: str
    what: str
    text: str = ""
    source: str = ""
    old: str = ""
    new: str = ""


@dataclass(frozen=True)
class Generation:
    """The source's generator step and the staged listing its output must match."""

    cwd: str
    argv: tuple[str, ...]
    outdir: str
    listing: str


@dataclass(frozen=True)
class Route:
    name: str
    result: str
    bead: str
    packet: str
    upstream: str
    project: str
    toolchain: str
    mathlib: str
    #: The ``devtools.lean_closure`` receipt of the upstream commit, repository-relative.
    closure: str
    files: tuple[Staged, ...]
    #: ``lake build`` invocations, in order; ``PARTS`` expands to one per generated part.
    builds: tuple[tuple[str, ...], ...]
    probe_imports: tuple[str, ...]
    theorems: tuple[str, ...]
    controls: tuple[Control, ...]
    generation: Generation | None = None
    parts_glob: str = ""
    notes: tuple[str, ...] = field(default_factory=tuple)


