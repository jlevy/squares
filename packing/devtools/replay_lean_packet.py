@dataclass(frozen=True)
class Staged:
    """One staged file: its path in the stage, its retained bytes, and what binds them.

    ``origin`` is repository-relative; a ``.gz`` holds the gzipped upstream bytes. A file
    is bound by the upstream SHA-256 (``sha256``), by its upstream Git blob (``blob``),
    or by both.
    """

    path: str
    origin: str
    sha256: str | None = None
    blob: str | None = None


@dataclass(frozen=True)
class Control:
    """A negative control the run must refuse.

    ``refused`` controls must make Lean exit non-zero with an error of their own, not a
    setup fault; ``sorry`` controls must print ``sorryAx`` among a theorem's axioms.
    A control with ``source`` is that staged file with ``old`` replaced by ``new``, where
    ``old`` occurs exactly once; otherwise ``text`` is the whole file.
    """

    name: str
    kind: str
    path: str
    what: str
    text: str = ""
    source: str = ""
    old: str = ""
    new: str = ""


@dataclass(frozen=True)
class Generation:
    """The source's generator step and the digests its output must have."""

    cwd: str
    argv: tuple[str, ...]
    outdir: str
    digests: str


@dataclass(frozen=True)
class Route:
    name: str
    result: str
    bead: str
    packet: str
    upstream: str
