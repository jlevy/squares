"""Join the result reports received as GitHub issues to the register, and say what each is owed.

An author who reports a result on an issue is owed three things by the result import
process (`campaign/result-import.md`, stage 7): a reply when the result is imported, one
when it is confirmed or a defect is found, a follow-up whenever the record moves past what
a reply said, and a final comment and close once nothing they asked for is queued. The
register says how far each result is validated. Nothing said which issue asked for which
entry, or what each author had been told, so replies went unposted (issue 170 was never
answered) and stated ids went stale (issue 247 still reads T-058 for T-061).

`campaign/result-requests.yaml` is that join: one entry per issue, the register and
evidence ids each reported result maps to, the beads that track it, and every reply
posted with the state it reported. This tool derives the rest from the record and the
register together and stores none of it:

- each result's state: `confirmed` (every mapped entry at `V3` and `C3` or above),
  `refuted`, `defect recorded`, `open` while validation runs, or `queued` for import;
- **reply due**, when the derived state has moved past the last reply that spoke of a
  result: a new id, a moved rung, a renumbered id, a defect, or a statement the record
  marks out of date;
- **closeable**, when every result is confirmed or refuted (a reported defect: recorded)
  and nothing the author asked for is queued.

Modes, from ``packing/`` with the project interpreter::

    .venv/bin/python3 -m devtools.check_requests            # the gate: ids and schema
    .venv/bin/python3 -m devtools.check_requests --report   # a table per issue
    .venv/bin/python3 -m devtools.check_requests --backlog  # entries below V3 or C3
    .venv/bin/python3 -m devtools.check_requests --draft 282
    .venv/bin/python3 -m devtools.check_requests --github   # live issues, read-only

The default mode reads two files and the register and touches no clock, network or
history, so its verdict is a function of the tree. Only the ids and the schema can fail
it: a reply that is due is the owner's next move, not a broken record. ``--draft``
refuses unless ``HEAD`` is on ``origin/main``, because a `T-NNN` is provisional until it
merges and a reply links only to `main`. ``--github`` reads the live issues through
``gh api`` and writes nothing anywhere.
"""

